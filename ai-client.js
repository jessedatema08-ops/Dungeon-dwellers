function featureState(name){return syncCharacterRuntime().classFeatures.find(f=>f.name.toLowerCase()===name.toLowerCase());}

function validateCharacterIntent(text){
  const profile=syncCharacterRuntime();
  const lower=text.toLowerCase();
  const castingIntent=/\b(?:i\s+)?cast(?:ing)?\b|\bcast\s+[a-z]|\buse\s+(?:a\s+)?spell\b|\bspell\s*:/i.test(text);
  if(castingIntent&&!profile.spellcasting.canCastSpells){
    return 'Character check: this character has no spellcasting feature or available spells, so that spell cannot be cast.';
  }
  if(/\bfireball\b/i.test(text)&&!profile.spellcasting.knownSpells.map(s=>s.toLowerCase()).includes('fireball')&&!profile.spellcasting.preparedSpells.map(s=>s.toLowerCase()).includes('fireball')){
    return 'Character check: Fireball is not on this character sheet and cannot be cast.';
  }
  if(/\bsecond wind\b/i.test(lower)){
    const f=featureState('Second Wind');if(!f||f.usesCurrent<1)return 'Character check: no Second Wind uses remain.';
  }
  if(/\baction surge\b/i.test(lower)){
    const f=featureState('Action Surge');if(!f||f.usesCurrent<1)return 'Character check: no Action Surge uses remain.';
  }
  if(/\bindomitable\b/i.test(lower))return 'Character check: Indomitable is not available to this level 5 Fighter.';
  return null;
}

function impossibleClaim(text){
  const dieClaim=/(?:rolled|roll|got|result(?:ed)?(?: in)?|came up)\s+(\d+)\s+(?:on\s+)?(?:a\s+)?d(4|6|8|10|12|20|100)\b/i.exec(text);
  if(dieClaim){const value=Number(dieClaim[1]),sides=Number(dieClaim[2]);if(value<1||value>sides)return `A d${sides} can only roll 1-${sides}. A claimed ${value} is invalid.`;}
  const reverse=/d(4|6|8|10|12|20|100)\s+(?:roll(?:ed)?|was|=|of)?\s*(\d+)/i.exec(text);
  if(reverse){const sides=Number(reverse[1]),value=Number(reverse[2]);if(value<1||value>sides)return `A d${sides} can only roll 1-${sides}. A claimed ${value} is invalid.`;}
  return null;
}

function detectRollRequest(text){
  if(!text)return null;const lower=text.toLowerCase();
  const asksRoll=/(make|roll|give me|attempt|perform).{0,35}(attack roll|damage roll|saving throw|save|ability check|skill check|initiative|concentration|death save|d20|d4|d6|d8|d10|d12|d100)/i.test(text)||/\broll\s+\d*d(?:4|6|8|10|12|20|100)\b/i.test(text);
  if(!asksRoll)return null;
  let label='Roll';if(lower.includes('attack roll'))label='Attack Roll';else if(lower.includes('damage roll'))label='Damage Roll';else if(lower.includes('saving throw')||/\bsave\b/.test(lower))label='Saving Throw';else if(lower.includes('ability check')||lower.includes('skill check'))label='Ability Check';else if(lower.includes('initiative'))label='Initiative';else if(lower.includes('concentration'))label='Concentration Save';else if(lower.includes('death save'))label='Death Save';
  const dice=/\b(\d{0,2})d(4|6|8|10|12|20|100)(?:\s*([+-])\s*(\d+))?/i.exec(text);
  if(dice){const count=Math.max(1,Math.min(20,Number(dice[1]||1))),sides=Number(dice[2]),mod=dice[3]?(dice[3]==='-'?-1:1)*Number(dice[4]||0):0;return {label,count,sides,mod,expression:`${count}d${sides}${mod?`${mod>0?'+':''}${mod}`:''}`,source:text};}
  if(label!=='Damage Roll')return {label,count:1,sides:20,mod:0,expression:'1d20',source:text};
  return {label,count:null,sides:null,mod:0,expression:null,source:text,needsDice:true};
}

