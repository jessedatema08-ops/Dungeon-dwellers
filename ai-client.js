async function handleMessage(message){
  if(pendingRoll){notice.textContent='A player roll is pending. Use the Roll in App button; typed roll results are not accepted.';return;}
  const invalid=impossibleClaim(message);if(invalid){notice.textContent=`Roll rejected: ${invalid} Use the app's roll prompt instead.`;return;}
  const characterProblem=validateCharacterIntent(message);if(characterProblem){notice.textContent=characterProblem;return;}
  sendBtn.disabled=true;notice.textContent='AI DM is checking your character and thinking…';if(status)status.textContent='AI DM thinking';
  try{const payload=await askAI(message);const narration=getNarration(payload);notice.textContent=`AI DM: ${narration}`;if(status)status.textContent='AI DM online';window.dispatchEvent(new CustomEvent('dungeon-dwellers-ai-response',{detail:payload}));const roll=detectRollRequest(narration);if(roll)setTimeout(()=>openRollPrompt(roll),250);}
  catch(err){console.error('Dungeon Dwellers AI error',err);const msg=err?.name==='AbortError'?'Request timed out after 45 seconds.':(err?.message||String(err));notice.textContent=`AI DM error: ${msg}`;if(status)status.textContent='AI DM offline';}
  finally{sendBtn.disabled=false;}
}

