  if(!pendingRoll||pendingRoll.needsDice)return;const btn=document.getElementById('aiRollBtn'),die=document.getElementById('aiRollDie'),math=document.getElementById('aiRollMath');btn.disabled=true;btn.textContent='Rolling';let ticks=0;const spin=setInterval(()=>{die.textContent=String(Math.floor(Math.random()*pendingRoll.sides)+1);if(++ticks>14){clearInterval(spin);finish();}},70);
  async function finish(){const rolls=Array.from({length:pendingRoll.count},()=>Math.floor(Math.random()*pendingRoll.sides)+1),total=rolls.reduce((a,b)=>a+b,0)+pendingRoll.mod;die.textContent=pendingRoll.count===1?String(rolls[0]):rolls.join(' + ');math.textContent=`${pendingRoll.expression} = ${total}`;const completed={...pendingRoll,rolls,total};pendingRoll=null;btn.textContent='Sending result to AI DM';try{const payload=await askAI(`APP_VERIFIED_ROLL: ${completed.label}; dice ${completed.expression}; raw rolls [${rolls.join(', ')}]; total ${total}. This result was generated by the app and is authoritative. Continue adjudication from this roll. Do not ask the player to type or invent a roll result.`,{verifiedSystemMessage:true});const narration=getNarration(payload);notice.textContent=`AI DM: ${narration}`;document.getElementById('aiRollOverlay').classList.remove('open');const next=detectRollRequest(narration);if(next)setTimeout(()=>openRollPrompt(next),250);if(status)status.textContent='AI DM online';}catch(err){math.textContent+=` · AI error: ${err?.message||String(err)}`;btn.disabled=false;btn.textContent='Retry sending result';pendingRoll=completed;}}
